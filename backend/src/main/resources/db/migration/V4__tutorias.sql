ALTER TABLE usuarios ADD COLUMN detalle VARCHAR(200) NOT NULL DEFAULT '';

CREATE TABLE avisos_leidos (
    usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    aviso_id VARCHAR(80) NOT NULL,
    PRIMARY KEY (usuario_id, aviso_id)
);

CREATE TABLE tutores (
    id VARCHAR(40) PRIMARY KEY,
    usuario_id BIGINT UNIQUE REFERENCES usuarios (id),
    nombre VARCHAR(150) NOT NULL,
    titulo VARCHAR(40) NOT NULL,
    area VARCHAR(150) NOT NULL,
    resumen VARCHAR(255) NOT NULL,
    calificacion DOUBLE PRECISION NOT NULL DEFAULT 0,
    sesiones INTEGER NOT NULL DEFAULT 0,
    lugar VARCHAR(150) NOT NULL,
    confirma_automatico BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE tutor_materias (
    tutor_id VARCHAR(40) NOT NULL REFERENCES tutores (id) ON DELETE CASCADE,
    posicion INTEGER NOT NULL,
    materia VARCHAR(150) NOT NULL,
    PRIMARY KEY (tutor_id, posicion)
);

CREATE TABLE tutor_experiencia (
    tutor_id VARCHAR(40) NOT NULL REFERENCES tutores (id) ON DELETE CASCADE,
    posicion INTEGER NOT NULL,
    texto VARCHAR(255) NOT NULL,
    PRIMARY KEY (tutor_id, posicion)
);

CREATE TABLE tutor_modalidades (
    tutor_id VARCHAR(40) NOT NULL REFERENCES tutores (id) ON DELETE CASCADE,
    modalidad VARCHAR(20) NOT NULL,
    PRIMARY KEY (tutor_id, modalidad)
);

CREATE TABLE tutor_formatos (
    tutor_id VARCHAR(40) NOT NULL REFERENCES tutores (id) ON DELETE CASCADE,
    formato VARCHAR(20) NOT NULL,
    PRIMARY KEY (tutor_id, formato)
);

CREATE TABLE tutor_horarios (
    tutor_id VARCHAR(40) NOT NULL REFERENCES tutores (id) ON DELETE CASCADE,
    inicio TIMESTAMP NOT NULL,
    PRIMARY KEY (tutor_id, inicio)
);

-- El id lo genera la app (UUID) para poder mostrar la solicitud antes de que responda el servidor.
CREATE TABLE solicitudes (
    id VARCHAR(40) PRIMARY KEY,
    tutor_id VARCHAR(40) NOT NULL REFERENCES tutores (id),
    estudiante_id BIGINT NOT NULL REFERENCES usuarios (id),
    tipo VARCHAR(20) NOT NULL,
    modalidad VARCHAR(20) NOT NULL,
    formato VARCHAR(20) NOT NULL,
    materia VARCHAR(150) NOT NULL,
    tema VARCHAR(255) NOT NULL,
    objetivo TEXT NOT NULL,
    archivo VARCHAR(255),
    inicio TIMESTAMP,
    estado VARCHAR(20) NOT NULL,
    nota TEXT,
    coordinacion_puede_ver BOOLEAN NOT NULL DEFAULT FALSE,
    asistio BOOLEAN,
    notas_sesion TEXT,
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX idx_solicitudes_tutor ON solicitudes (tutor_id);
CREATE INDEX idx_solicitudes_estudiante ON solicitudes (estudiante_id);

CREATE TABLE solicitud_companeros (
    solicitud_id VARCHAR(40) NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
    posicion INTEGER NOT NULL,
    correo VARCHAR(255) NOT NULL,
    PRIMARY KEY (solicitud_id, posicion)
);

CREATE TABLE mensajes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id VARCHAR(40) NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
    autor_id BIGINT NOT NULL REFERENCES usuarios (id),
    texto TEXT NOT NULL,
    enviado_en TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_mensajes_solicitud ON mensajes (solicitud_id, id);

-- Un código activo por correo, para registro o recuperación de contraseña.
CREATE TABLE codigos (
    correo VARCHAR(255) PRIMARY KEY,
    proposito VARCHAR(20) NOT NULL,
    codigo_hash VARCHAR(255) NOT NULL,
    expira TIMESTAMP WITH TIME ZONE NOT NULL,
    intentos INTEGER NOT NULL DEFAULT 0
);
